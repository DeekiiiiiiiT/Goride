export function kindFor(act: string, screen = ''): string | null {
  if (!act) return null;
  if (EXACT[act]) return EXACT[act];
  if (act.startsWith('otp-') || /^[0-9]$/.test(act)) return 'otp-digit';
  if (/^class-btn-/.test(act)) return 'toggle';
  for (const [pattern, kind] of PATTERNS) {
    if (pattern.test(act)) return kind;
  }
  if (screen.includes('help')) return 'toggle';
  if (screen.includes('filters')) return 'toggle';
  if (screen.includes('settings') || screen.includes('notification')) return 'toggle';
  if (screen.includes('tolls')) return 'tolls';
  if (screen.includes('parts')) return 'part-row';
  if (screen.includes('maintenance') || screen.includes('service')) return 'service';
  if (screen.includes('document')) return 'documents';
  if (screen.includes('place') || screen.includes('pin') || screen.includes('map')) return 'map';
  if (screen.includes('account') || screen.includes('privacy')) return 'account';
  if (screen.includes('garage') || screen.includes('vehicle')) return 'garage';
  if (screen.includes('fuel') || screen.includes('odometer') || screen.includes('saved')) return 'log-fuel';
  if (screen.includes('explore') || screen.includes('search') || screen.includes('station') || screen.includes('guest') || screen.includes('offline')) return 'explore';
  if (screen.includes('inbox') || screen.includes('notification')) return 'inbox';
  if (screen.includes('how') || screen.includes('welcome') || screen.includes('splash') || screen.includes('login') || screen.includes('signup') || screen.includes('otp') || screen.includes('profile') || screen.includes('consent') || screen.includes('permission')) return 'primary';
  return null;
}
