#!/usr/bin/env node
/**
 * Generate supabase/tests/toll_v2_week_rule.sql from weekRuleCases.json.
 * Usage:
 *   node scripts/gen-toll-week-rule-sql.mjs
 *   node scripts/gen-toll-week-rule-sql.mjs --check
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const JSON_PATH = path.join(
  ROOT,
  'packages/toll-core/src/v2/weekRuleCases.json',
);
const OUT_SQL = path.join(ROOT, 'supabase/tests/toll_v2_week_rule.sql');

function escSqlLiteral(s) {
  return String(s).replace(/'/g, "''");
}

export function renderTollWeekRuleSql() {
  const cases = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
  const checks = cases
    .map(
      (c, i) =>
        `  IF ledger.jamaica_week_start('${escSqlLiteral(c.at)}'::timestamptz) IS DISTINCT FROM '${escSqlLiteral(c.week)}'::date THEN\n` +
        `    RAISE EXCEPTION 'toll_v2_week_rule case ${i + 1}: at % expected % got %', '${escSqlLiteral(c.at)}', '${escSqlLiteral(c.week)}', ledger.jamaica_week_start('${escSqlLiteral(c.at)}'::timestamptz);\n` +
        `  END IF;`,
    )
    .join('\n\n');

  return `-- GENERATED by scripts/gen-toll-week-rule-sql.mjs — do not edit.
-- Week rule drift: ledger.jamaica_week_start must match packages/toll-core/src/v2/weekRuleCases.json

DO $$
BEGIN
${checks}

  RAISE NOTICE 'toll_v2_week_rule: ok';
END;
$$;
`;
}

export function weekRuleSqlDrift() {
  if (!fs.existsSync(OUT_SQL)) return 'missing';
  const committed = fs.readFileSync(OUT_SQL, 'utf8').replace(/\r\n/g, '\n');
  const rendered = renderTollWeekRuleSql().replace(/\r\n/g, '\n');
  if (committed !== rendered) return 'stale';
  return null;
}

const isDirect =
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isDirect) {
  if (process.argv.includes('--check')) {
    const drift = weekRuleSqlDrift();
    if (drift) {
      console.error(
        `FAIL: ${OUT_SQL} is ${drift} — re-run node scripts/gen-toll-week-rule-sql.mjs and commit`,
      );
      process.exit(1);
    }
    console.log('ok  toll_v2_week_rule.sql');
  } else {
    fs.writeFileSync(OUT_SQL, renderTollWeekRuleSql());
    console.log('Wrote', OUT_SQL);
  }
}
