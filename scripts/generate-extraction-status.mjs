/**
 * Derive extraction-status from committed route manifests (B5 / Phase 6).
 * Usage:
 *   node scripts/generate-extraction-status.mjs
 *   node scripts/generate-extraction-status.mjs --check
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const DOMAINS = [
  { key: "fuel", slug: "fleet-fuel" },
  { key: "toll", slug: "fleet-toll" },
  { key: "ops", slug: "fleet-ops" },
  { key: "claims", slug: "fleet-claims" },
  { key: "pay", slug: "fleet-pay" },
];

const outTs = path.join(
  ROOT,
  "supabase/functions/_shared/extractionStatus.generated.ts",
);

function buildPayload() {
  const domains = {};
  for (const d of DOMAINS) {
    const manifestPath = path.join(
      ROOT,
      "supabase/functions",
      d.slug,
      "routes.generated.json",
    );
    const exists = fs.existsSync(manifestPath);
    let routeCount = 0;
    if (exists) {
      const m = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
      routeCount = m.routeCount ?? (m.routes?.length ?? 0);
    }
    domains[d.key] = {
      slug: d.slug,
      cutover: exists && routeCount > 0 ? "done" : "pending",
      routeCount,
    };
  }

  const coreManifest = path.join(
    ROOT,
    "supabase/functions/fleet-core/src/main.ts",
  );
  return {
    shim: null,
    fleetCoreScaffolded: fs.existsSync(coreManifest),
    domains,
  };
}

export function renderExtractionStatus() {
  return `/** GENERATED by scripts/generate-extraction-status.mjs — do not edit. */
export const extractionStatus = ${JSON.stringify(buildPayload(), null, 2)} as const;
`;
}

export function writeExtractionStatus() {
  fs.writeFileSync(outTs, renderExtractionStatus());
  console.log("Wrote", outTs);
}

/** Route manifests are the source; this file must match them or deploy rejects the push. */
export function extractionStatusDrift() {
  if (!fs.existsSync(outTs)) return "missing";
  const committed = fs.readFileSync(outTs, "utf8").replace(/\r\n/g, "\n");
  if (committed !== renderExtractionStatus()) return "stale";
  return null;
}

const isDirect = process.argv[1]
  && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isDirect) {
  if (process.argv.includes("--check")) {
    const drift = extractionStatusDrift();
    if (drift) {
      console.error(
        "FAIL: extractionStatus.generated.ts is stale — re-run generate-extraction-status.mjs and commit",
      );
      process.exit(1);
    }
    console.log("ok  extractionStatus.generated.ts");
  } else {
    writeExtractionStatus();
  }
}
