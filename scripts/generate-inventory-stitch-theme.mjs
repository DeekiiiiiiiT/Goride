#!/usr/bin/env node
/**
 * Merge fleet inventory Stitch tailwind tokens into apps/fleet inventory.css scope.
 * Usage: node scripts/generate-inventory-stitch-theme.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { generateScopedStitchCss, parseTailwindConfigFromHtml } from './stitch-tailwind-theme.mjs';

const repo = join(dirname(import.meta.dirname), '..');
const htmlPath = join(
  repo,
  'docs/stitch/roam-fleet-app/inventory/inventory_asset_management_stock/code.html',
);
const outPath = join(repo, 'apps/fleet/src/components/inventory/inventory.css');

if (!existsSync(htmlPath)) {
  console.error('Missing stitch stock html:', htmlPath);
  process.exit(1);
}

const cfg = parseTailwindConfigFromHtml(htmlPath);
const generated = generateScopedStitchCss('fleet-inventory-stitch', cfg.theme?.extend ?? cfg.theme ?? {});
const banner = `/* Generated by scripts/generate-inventory-stitch-theme.mjs — do not hand-edit tokens */\n`;
const base = readFileSync(outPath, 'utf8').split('/* Generated by')[0];
writeFileSync(outPath, base + banner + generated + '\n');
console.log('Updated', outPath);
